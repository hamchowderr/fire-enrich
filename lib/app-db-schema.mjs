/**
 * The app's own tables in the libSQL database: business profiles and saved
 * research plans. Mastra's tables live in the same database (see
 * `lib/libsql-url.mjs`) and are created by Mastra itself; nothing here touches
 * them.
 *
 * Applied by `npm run db:migrate:libsql` (`scripts/libsql-migrate.mjs`), which
 * the Vercel build runs whenever `TURSO_DATABASE_URL` is set, and by
 * `lib/app-db.ts` on first use when the database is a local file, so a fresh
 * clone needs no migration step.
 *
 * Every statement is `IF NOT EXISTS`, so the whole list is safe to re-apply
 * and a second run changes nothing. The rules of `db/schema.sql` hold here
 * too: the migration runs while the previous deployment still serves traffic,
 * so changes must be additive (new tables, nullable columns, columns with
 * defaults, non-unique indexes), never a drop or a rename in the same release
 * as the code that stops using it.
 *
 * SQLite column types: ids and text are `TEXT`; the JSON columns are `TEXT`
 * holding JSON, checked with `json_valid` so a write can never store a value
 * the read path cannot parse; timestamps are `TEXT` in SQLite's
 * `CURRENT_TIMESTAMP` form, `YYYY-MM-DD HH:MM:SS` in UTC, the same string the
 * Dolt tables returned for these rows.
 *
 * Plain `.mjs` with no dependencies so the migration script can import it
 * under plain Node.
 */

/** Every statement, in order. */
export const APP_DB_STATEMENTS = /** @type {const} */ ([
  // A business profile: who the business is, what it sells, who it sells to,
  // and the defaults the planner assumes when the operator does not say
  // otherwise. Ids are nanoids generated by the app.
  `CREATE TABLE IF NOT EXISTS profiles (
    id TEXT NOT NULL PRIMARY KEY,
    name TEXT NOT NULL,
    business_summary TEXT NOT NULL,
    offer TEXT NOT NULL,
    audiences TEXT NOT NULL CHECK (json_valid(audiences)),
    default_field_hints TEXT NOT NULL CHECK (json_valid(default_field_hints)),
    crm_defaults TEXT NOT NULL CHECK (json_valid(crm_defaults)),
    models TEXT NOT NULL CHECK (json_valid(models)),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  // Unique so two profiles cannot be confused in a picker. Case-sensitive
  // (SQLite's BINARY collation), as the Dolt column was.
  'CREATE UNIQUE INDEX IF NOT EXISTS uq_profiles_name ON profiles (name)',
  'CREATE INDEX IF NOT EXISTS idx_profiles_created_at ON profiles (created_at)',

  // A research plan the planner produced for one profile. `plan` is the whole
  // ResearchPlan as JSON: its shape is the planner's to change. Quoted because
  // PLAN is a keyword in SQLite (EXPLAIN QUERY PLAN). The reference to the
  // profile is declared, and the app also enforces it itself (see
  // `lib/plans.ts`), so behaviour does not depend on whether a connection has
  // `PRAGMA foreign_keys` on.
  `CREATE TABLE IF NOT EXISTS research_plans (
    id TEXT NOT NULL PRIMARY KEY,
    profile_id TEXT NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    goal TEXT NOT NULL,
    audience TEXT NULL,
    "plan" TEXT NOT NULL CHECK (json_valid("plan")),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  'CREATE INDEX IF NOT EXISTS idx_research_plans_profile_id ON research_plans (profile_id)',
  'CREATE INDEX IF NOT EXISTS idx_research_plans_created_at ON research_plans (created_at)',
]);

/**
 * The schema objects (tables and indexes) that exist, as `type:name`, sorted.
 * Compared before and after a migration to report what it changed.
 *
 * @param {{ execute(sql: string): Promise<{ rows: ArrayLike<Record<string, unknown>> }> }} client
 * @returns {Promise<string[]>}
 */
async function schemaObjects(client) {
  const result = await client.execute(
    "SELECT type, name FROM sqlite_master WHERE type IN ('table', 'index') AND name NOT LIKE 'sqlite_%' ORDER BY type, name"
  );
  return Array.from(result.rows, (row) => `${row.type}:${row.name}`);
}

/**
 * Apply {@link APP_DB_STATEMENTS} in one write batch, which libSQL runs as one
 * transaction: either every statement lands or none does. Returns the schema
 * objects the run created; empty means the database was already up to date.
 *
 * @param {{
 *   execute(sql: string): Promise<{ rows: ArrayLike<Record<string, unknown>> }>,
 *   batch(statements: string[], mode: 'write'): Promise<unknown>,
 * }} client A `@libsql/client` Client.
 * @returns {Promise<string[]>}
 */
export async function applyAppDbSchema(client) {
  const before = new Set(await schemaObjects(client));
  await client.batch([...APP_DB_STATEMENTS], 'write');
  return (await schemaObjects(client)).filter((name) => !before.has(name));
}
